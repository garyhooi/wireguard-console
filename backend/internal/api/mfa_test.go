func TestTOTPVerifyRoundTrip(t *testing.T) {
	key, err := auth.GenerateTOTP()
	if err != nil {
		t.Fatalf("GenerateTOTP: %v", err)
	}
	code, err := totp.GenerateCode(key.Secret(), time.Now())
	if err != nil {
		t.Fatalf("GenerateCode: %v", err)
	}
	if !auth.VerifyTOTP(key.Secret(), code) {
		t.Error("fresh authenticator code must verify")
	}
	if auth.VerifyTOTP(key.Secret(), "000000") && code != "000000" {
		t.Error("wrong code must not verify")
	}
	if !strings.HasPrefix(key.URL(), "otpauth://totp/") {
		t.Errorf("otpauth URL %q is malformed", key.URL())
	}
}

func TestTOTPChallengeHashNamespacing(t *testing.T) {
	adminA := uuid.New()
	adminB := uuid.New()

	a1 := totpChallengeHash(totpEnrollBindingPrefix, "pending-hash", adminA)
	a2 := totpChallengeHash(totpEnrollBindingPrefix, "pending-hash", adminA)
	if a1 != a2 {
		t.Error("challenge hash must be deterministic")
	}
	if a1 == totpChallengeHash(totpEnrollBindingPrefix, "other-pending", adminA) {
		t.Error("challenge hash must depend on the binding")
	}
	if a1 == totpChallengeHash(totpEnrollBindingPrefix, "pending-hash", adminB) {
		t.Error("challenge hash must depend on the admin")
	}
	if a1 == totpChallengeHash(totpAddBindingPrefix, "pending-hash", adminA) {
		t.Error("enroll and add flows must not share a challenge")
	}
}

