func TestMFAFactorsEnrolledAndMethods(t *testing.T) {
	if (mfaFactors{}).Enrolled() {
		t.Error("zero factors must not count as enrolled")
	}
	totpOnly := mfaFactors{TOTPEnabled: true}
	if !totpOnly.Enrolled() {
		t.Error("TOTP must count as enrolled")
	}
	if got := totpOnly.methods(true); len(got) != 1 || got[0] != mfaMethodTOTP {
		t.Errorf("TOTP-only methods = %v, want [totp]", got)
	}

	both := mfaFactors{TOTPEnabled: true, PasskeyCount: 2, RecoveryCodeCount: 10}
	got := both.methods(true)
	want := []string{mfaMethodPasskey, mfaMethodTOTP, mfaMethodRecoveryCode}
	if len(got) != len(want) {
		t.Fatalf("both-factor methods = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("both-factor methods = %v, want %v", got, want)
		}
	}
	// A passkey that cannot run a ceremony in this deployment is not offered.
	if got := both.methods(false); len(got) != 2 || got[0] != mfaMethodTOTP {
		t.Errorf("methods(passkey unavailable) = %v, want [totp recovery_code]", got)
	}
}

func TestPolicySatisfied(t *testing.T) {
	totpOnly := mfaFactors{TOTPEnabled: true}
	passkeyOnly := mfaFactors{PasskeyCount: 1}
	both := mfaFactors{TOTPEnabled: true, PasskeyCount: 1}
	none := mfaFactors{RecoveryCodeCount: 5} // recovery codes are not a login factor

	cases := []struct {
		name     string
		policy   string
		factors  mfaFactors
		passkeys bool
		want     bool
	}{
		{"any/no-factor", mfaPolicyAny, none, true, false},
		{"any/totp", mfaPolicyAny, totpOnly, true, true},
		{"any/passkey", mfaPolicyAny, passkeyOnly, true, true},
		{"any/passkey-unavailable", mfaPolicyAny, passkeyOnly, false, false},
		{"totp/totp", mfaPolicyTOTP, totpOnly, true, true},
		{"totp/passkey", mfaPolicyTOTP, passkeyOnly, true, false},
		{"passkey/passkey", mfaPolicyPasskey, passkeyOnly, true, true},
		{"passkey/unavailable", mfaPolicyPasskey, passkeyOnly, false, false},
		{"both/totp", mfaPolicyBoth, totpOnly, true, false},
		{"both/both", mfaPolicyBoth, both, true, true},
		{"unknown-falls-back-to-any", "garbage", totpOnly, true, true},
	}
	for _, c := range cases {
		if got := policySatisfied(c.policy, c.factors, c.passkeys); got != c.want {
			t.Errorf("%s: policySatisfied = %v, want %v", c.name, got, c.want)
		}
	}
}

