// ---- recovery codes ------------------------------------------------------

func TestGenerateRecoveryCodeShape(t *testing.T) {
	seen := map[string]bool{}
	for i := 0; i < 100; i++ {
		code, err := generateRecoveryCode()
		if err != nil {
			t.Fatalf("generateRecoveryCode: %v", err)
		}
		if len(code) != recoveryCodeLength {
			t.Fatalf("code %q has length %d, want %d", code, len(code), recoveryCodeLength)
		}
		for _, r := range code {
			if !strings.ContainsRune(recoveryCodeAlphabet, r) {
				t.Fatalf("code %q contains a character outside the unambiguous alphabet: %q", code, r)
			}
		}
		if seen[code] {
			t.Fatalf("duplicate recovery code generated: %q", code)
		}
		seen[code] = true
	}
}

func TestNormalizeRecoveryCode(t *testing.T) {
	cases := map[string]string{
		"abcd-efgh-2345":  "ABCDEFGH2345",
		" ABCD EFGH 2345": "ABCDEFGH2345",
		"abcd efgh 2345":  "ABCDEFGH2345",
		"----":            "",
		"":                "",
	}
	for in, want := range cases {
		if got := normalizeRecoveryCode(in); got != want {
			t.Errorf("normalizeRecoveryCode(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestRecoveryCodeHashSaltsAndNormalizes(t *testing.T) {
	adminA := uuid.New()
	adminB := uuid.New()
	code := "abcd-efgh-2345"

	hashA := recoveryCodeHash(adminA, code)
	if !strings.HasPrefix(hashA, recoveryCodeHashPrefix) {
		t.Fatalf("recovery hash %q does not carry the version prefix", hashA)
	}
	if hashA != recoveryCodeHash(adminA, "ABCDEFGH2345") {
		t.Error("recovery hash must normalize case/formatting")
	}
	if hashA != recoveryCodeHash(adminA, code) {
		t.Error("recovery hash must be deterministic")
	}
	if hashA == recoveryCodeHash(adminB, code) {
		t.Error("recovery hash must be salted with the admin id")
	}
	if strings.Contains(hashA, "ABCDEFGH") {
		t.Error("recovery hash must not contain the plaintext code")
	}
}

func TestLegacyRecoveryCodeHashStillRecognised(t *testing.T) {
	// Pre-MFA codes were 8-char lowercase hex hashed with a bare sha256.
	legacy := "d4e5f6a7" // 8 hex chars, as generated by auth.GenerateBackupCodes
	got := legacyRecoveryCodeHash(legacy)
	if !strings.EqualFold(got, legacyRecoveryCodeHash(strings.ToUpper(legacy))) {
		t.Error("legacy recovery hash must normalize case")
	}
	if got == recoveryCodeHash(uuid.New(), legacy) {
		t.Error("legacy hash must differ from the salted modern hash")
	}
	if len(got) != 64 {
		t.Fatalf("legacy hash length = %d, want a sha256 hex digest", len(got))
	}
}

